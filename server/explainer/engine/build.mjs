// Bundles the engine, the catalog and the kit into one browser script (the `SceneEngine`
// global) plus its stylesheet. Packages and the stream demo both inline these two files.
import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ISO_CSS } from "../vendor/anatomy/kit/iso-kit.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));

export async function buildEngine() {
  const started = performance.now();
  const result = await build({
    entryPoints: [join(HERE, "browser.mjs")],
    bundle: true,
    format: "iife",
    globalName: "SceneEngine",
    target: "es2020",
    minify: true,
    legalComments: "none",
    write: false,
  });
  const script = result.outputFiles[0].text;
  const css = ISO_CSS + readFileSync(join(HERE, "engine.css"), "utf8");
  mkdirSync(join(HERE, "dist"), { recursive: true });
  writeFileSync(join(HERE, "dist", "engine.js"), script);
  writeFileSync(join(HERE, "dist", "engine.css"), css);
  // The same bundle, styles and prompt example as one importable module, for runtimes without
  // a filesystem (the Cloudflare Worker).
  const example = readFileSync(join(HERE, "examples", "spring-scale.jsonl"), "utf8").trim();
  writeFileSync(join(HERE, "dist", "engine-source.mjs"), `// Generated by engine/build.mjs. Do not edit.\nexport const script = ${JSON.stringify(script)};\nexport const css = ${JSON.stringify(css)};\nexport const example = ${JSON.stringify(example)};\n`);
  return { script, css, ms: performance.now() - started };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { script, css, ms } = await buildEngine();
  console.log(`engine.js ${(script.length / 1024).toFixed(1)} KB · engine.css ${(css.length / 1024).toFixed(1)} KB · ${ms.toFixed(0)} ms`);
}
